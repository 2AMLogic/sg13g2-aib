#!/usr/bin/env python3
"""Aggregate the committed per-row records into the T1 item 8 characterization report.

Reads the T-NN rows of spec/target-spec.md and measurements/row-evidence.json, writes
measurements/characterization-report.md and signoff/attest/item8.json (a bare `generic`
envelope that pins the report's sha256). It only reads committed records; it runs no
simulation.

  python3 -I scripts/ci/gen_characterization_report.py            # write
  python3 -I scripts/ci/gen_characterization_report.py --check    # exit 1 on any diff
"""
import argparse
import hashlib
import json
import operator
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent.parent
SPEC = "spec/target-spec.md"
MAP = "measurements/row-evidence.json"
REPORT = "measurements/characterization-report.md"
ENVELOPE = "signoff/attest/item8.json"
OPS = {">=": operator.ge, "<=": operator.le, "==": operator.eq}
STA = [("clk", "signoff/attest/item5-digital/sta_clk.json"),
       ("rx_clk", "signoff/attest/item5-digital/sta_rx_clk.json")]
PNR = "layout/pnr/request.report.json"
NYM = "not-yet-measured"


def load(root, rel):
    return json.loads((root / rel).read_text())


def spec_rows(root):
    rows = []
    for line in (root / SPEC).read_text().splitlines():
        m = re.match(r"\| (T-\d\d) \|", line)
        if m:
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            rows.append((cells[0], cells[1]))
    return rows


def pick(obj, path):
    for part in re.findall(r"[^.\[\]]+(?:\[[^\]]+\])?", path):
        m = re.fullmatch(r"(\w+)\[(\w+)=([^\]]+)\]", part)
        if m:
            obj = next(i for i in obj[m.group(1)] if i.get(m.group(2)) == m.group(3))
        else:
            obj = obj[part]
    return obj


def evaluate(root, ev):
    rec = load(root, ev["record"])
    got = pick(rec, ev["field"])
    want = pick(rec, ev["value_field"]) if "value_field" in ev else ev["value"]
    return got, want, OPS[ev["op"]](got, want)


def link(rel):
    return f"[`{rel}`](../{rel})"


def row_table(root, rows, mapping):
    out = ["| ID | Parameter | Measured | Binding corner | Scope | Status | Record |", "|---|---|---|---|---|---|---|"]
    counts = {"pass": 0, "fail": 0, NYM: 0}
    for rid, name in rows:
        evs = mapping.get(rid, [])
        if not evs:
            counts[NYM] += 1
            out.append(f"| {rid} | {name} | — | — | — | {NYM} | — |")
            continue
        results = [evaluate(root, e) for e in evs]
        status = "pass" if all(r[2] for r in results) else "fail"
        counts[status] += 1
        meas = "<br>".join(f"{e['basis']}: {g} (needs {e['op']} {w})" for e, (g, w, _) in zip(evs, results))
        corner = "<br>".join(dict.fromkeys(e["corner"] for e in evs))
        scope = "<br>".join(dict.fromkeys(e["scope"] for e in evs))
        recs = "<br>".join(dict.fromkeys(link(e["record"]) for e in evs))
        notes = " ".join(dict.fromkeys(e["note"] for e in evs if e.get("note")))
        out.append(f"| {rid} | {name} | {meas}<br>_{notes}_ | {corner} | {scope} | {status} | {recs} |")
    return out, counts


def digital_table(root):
    out = ["| Source | Clock / run | Corner | Fmax (MHz) | Worst setup slack (ns) | Power (mW) |", "|---|---|---|---|---|---|"]
    for clk, rel in STA:
        for c in load(root, rel)["corners"]:
            out.append(f"| {link(rel)} | {clk} | {c['corner']} | {c['fmax_mhz']} | {c['worst_slack_ns']} | {c['estimated_power_mw']} |")
    p = load(root, PNR)
    out.append(f"| {link(PNR)} | place-and-route headline | as reported by `klt place-and-route` | {p['fmax_mhz']} | {p['worst_slack_ns']} | {p['estimated_power_mw']} |")
    area = ["| Source | Die area (µm²) | Core area (µm²) | Utilization (%) |", "|---|---|---|---|",
            f"| {link(PNR)} | {p['die_area_um2']} | {p['core_area_um2']} | {p['utilization_pct']} |"]
    return out, area


def build_report(root):
    rows = spec_rows(root)
    if len(rows) != 30:
        sys.exit(f"expected 30 spec rows T-01..T-30, found {len(rows)}")
    mapping = json.loads((root / MAP).read_text())["rows"]
    unknown = sorted(set(mapping) - {r for r, _ in rows})
    if unknown:
        sys.exit(f"{MAP} names rows not in the spec: {unknown}")
    table, counts = row_table(root, rows, mapping)
    dig, area = digital_table(root)
    text = "\n".join([
        "# Characterization report (T1 item 8)",
        "",
        "Generated by `scripts/ci/gen_characterization_report.py` from the committed records; do not edit by hand.",
        f"Row-to-record map: {link(MAP)}. Spec: {link(SPEC)}.",
        "",
        f"**Read this first.** {counts['pass']} of 30 rows have a recorded value that meets its target, "
        f"{counts['fail']} fail, and {counts[NYM]} are `{NYM}`. Item 8 reading `met` means this aggregate exists and "
        "no recorded row fails; it does not mean the 30 rows pass. Every `not-yet-measured` row is an open gap, "
        "owned by the analog PVT and Monte Carlo work. No spec target or fallback was changed to produce this table.",
        "",
        "Scope labels follow the spec: CH is the modeled die-to-die channel, TC is the test configuration "
        "(loopback, wire bond). A value that exists only for TC is labelled TC.",
        "",
        "## Per-row results (T-01..T-30)",
        "",
        *table,
        "",
        "## Digital partition: Fmax, area, power",
        "",
        "Fmax and power are STA / netlist estimates (`geometry_source: netlist_estimate` for the `sta_*` rows, "
        "ideal clock, default activity), not silicon measurements. Area is the placed-and-routed figure. "
        "Only the two STA corners exist; there is no typical corner in the STA records.",
        "",
        *dig,
        "",
        *area,
        "",
    ])
    return text, counts


def build_envelope(text, counts):
    digest = "sha256:" + hashlib.sha256(text.encode()).hexdigest()
    env = {
        "schema_version": 1,
        "kind": "generic",
        "status": "fail" if counts["fail"] else "pass",
        "t1_item": 8,
        "summary": (f"T1 item 8 (Characterization report): {counts['pass']} pass, {counts['fail']} fail, "
                    f"{counts[NYM]} {NYM} of 30 spec rows; status pass means no recorded row fails"),
        "source": REPORT,
        "metrics": {"rows_total": 30, "rows_pass": counts["pass"], "rows_fail": counts["fail"],
                    "rows_not_yet_measured": counts[NYM]},
        "provenance": {"klt_version": None, "input": {"path": {"path": REPORT, "scope": "repo"}, "content_hash": digest}},
    }
    return json.dumps(env, indent=2) + "\n", digest


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="regenerate in memory; exit 1 on any diff")
    ap.add_argument("--root", type=Path, default=REPO)
    a = ap.parse_args()
    text, counts = build_report(a.root)
    env, digest = build_envelope(text, counts)
    want = {REPORT: text, ENVELOPE: env}
    if a.check:
        bad = [p for p, t in want.items() if not (a.root / p).is_file() or (a.root / p).read_text() != t]
        if bad:
            print("stale (regenerate, then re-cite the hash in the manifest): " + ", ".join(bad), file=sys.stderr)
            return 1
        man = json.loads((a.root / "signoff/block-manifest.json").read_text())["evidence"]
        for k in ("8.analog", "8.digital"):
            if man.get(k, {}).get("content_hash") != digest:
                print(f"manifest {k} does not cite {digest}", file=sys.stderr)
                return 1
        print(f"ok {digest}")
        return 0
    for p, t in want.items():
        (a.root / p).write_text(t)
    print(f"wrote {REPORT}, {ENVELOPE}; cite {digest} under 8.analog and 8.digital")
    return 0


if __name__ == "__main__":
    sys.exit(main())
