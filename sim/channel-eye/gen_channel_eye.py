#!/usr/bin/env python3
"""Generate the channel-eye stimulus include and the two `klt sim` requests.

Stdlib only. Usage (from anywhere):
  python3 -I sim/channel-eye/gen_channel_eye.py          # write the generated files
  python3 -I sim/channel-eye/gen_channel_eye.py --check  # exit 1 if they are stale

Generated: prbs7_stim.inc, request_ch_1g.json, request_tc_1g.json, request_ctl_ch_tt.json.

Timing: UI 1000 ps (1 Gb/s DDR, 500 MHz forwarded clock). The stimulus is the cyclic
PRBS-7 sequence (x^7 + x^6 + 1) with the last WARM bits prepended, so the waveform is
periodic from t = 0 and every measurement window of 127 UI sees each 7-bit pattern once.
Data bit i occupies [i UI, (i+1) UI) with a TR-long ramp starting at i UI; the clock
toggles at (i + 0.5) UI (center aligned), so the nominal data-to-clock offset is UI/2.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
UI_PS = 1000
TR_PS = 100
WARM = 14                 # warm-up bits (cyclic prefix), excluded from every window
PERIOD = 127
NBITS = WARM + PERIOD     # 141 UI total
T0_NS, T1_NS = WARM * UI_PS // 1000, NBITS * UI_PS // 1000
N_WIRES = 20              # data wires per forwarded clock (T-03)
EYE_STEP_PS = 50          # 0.05 UI phase step of the eye-window search
EYE_WIN_PS = 400          # 0.40 UI (T-18)
EYE_H_V = 0.09            # +-90 mV (T-18)
SUPPLIES = ["vdd_atx", "vdd_arx", "vdd_btx", "vdd_brx", "vdd_ctx", "vdd_crx"]
RX = {"a": "vdd_arx", "b": "vdd_brx", "c": "vdd_crx", "cb": "vdd_crx"}
PINS = {"a": "rxa", "b": "rxb", "c": "rxc", "cb": "rxcb"}
OSDI = ["psp103", "psp103_nqs", "r3_cmc", "mosvar"]
# MOS corner -> (resistor section, diode section) of the PDK corner libraries
PROCESS = {"mos_tt": ("res_typ", "dio_tt"), "mos_ss": ("res_wcs", "dio_ss"),
           "mos_ff": ("res_bcs", "dio_ff"), "mos_sf": ("res_typ", "dio_tt"),
           "mos_fs": ("res_typ", "dio_tt")}
MODELS = "libs.tech/ngspice/models/"


def prbs7():
    s, out, seen = 0x7F, [], set()
    for _ in range(PERIOD):
        seen.add(s)
        out.append(s & 1)
        s = (s >> 1) | (((s ^ (s >> 1)) & 1) << 6)  # taps 7,6 (Fibonacci)
    assert len(seen) == PERIOD and s == 0x7F, "not a maximal-length sequence"
    return out


def stream():
    p = prbs7()
    return [p[(i - WARM) % PERIOD] for i in range(NBITS)]


def transitions(bits):
    """[(i, 'rise'|'fall', run_len_before)] for i >= 1."""
    out, run = [], 1
    for i in range(1, len(bits)):
        if bits[i] != bits[i - 1]:
            out.append((i, "rise" if bits[i] else "fall", run))
            run = 1
        else:
            run += 1
    return out


def pwl(points):
    return " ".join(f"{t * 1e-12:.6g} {v}" for t, v in points)


def lane_pwl(levels_at):
    """levels_at: [(edge_start_ps, level)] with an implied initial level first."""
    (_, v0), rest = levels_at[0], levels_at[1:]
    pts, cur = [(0, v0)], v0
    for t, v in rest:
        pts += [(t, cur), (t + TR_PS, v)]
        cur = v
    pts.append((NBITS * UI_PS, cur))
    return pts


def stim_include():
    b = stream()
    data = [(0, b[0])] + [(i * UI_PS, b[i]) for i in range(1, NBITS) if b[i] != b[i - 1]]
    comp = [(t, 1 - v) for t, v in data]
    clk = [(0, 0)] + [(j * UI_PS + UI_PS // 2, 1 if j % 2 == 0 else 0) for j in range(NBITS)]
    clkb = [(t, 1 - v) for t, v in clk]
    lines = [
        "* prbs7_stim.inc -- GENERATED by gen_channel_eye.py; do not edit.",
        f"* PRBS-7 (x^7+x^6+1), cyclic, {WARM} warm-up bits + {PERIOD}; UI {UI_PS} ps, ramp {TR_PS} ps.",
        "* Normalised 0..1 levels; tb_body.inc scales them by the TX supply.",
    ]
    for name, node, pts in (("pa", "pa", data), ("pb", "pb", comp), ("pc", "pc", clk), ("pcb", "pcb", clkb)):
        lines.append(f"V{name} {node} 0 dc 0 pwl({pwl(lane_pwl(pts))})")
    return "\n".join(lines) + "\n"


def skew_pairs():
    """Measurement edge selections: (name, trig-expr args) for T-15 and T-16."""
    b = stream()
    tr = [t for t in transitions(b) if 15 <= t[0] <= 130]
    rises_before = lambda i: sum(1 for t in transitions(b) if t[1] == "rise" and t[0] <= i)
    falls_before = lambda i: sum(1 for t in transitions(b) if t[1] == "fall" and t[0] <= i)
    pick = lambda pol, long_: sorted((t for t in tr if t[1] == pol), key=lambda t: (-t[2] if long_ else t[2], t[0]))
    t15, t16 = [], []
    for pol in ("rise", "fall"):
        for ctx, long_ in (("long", True), ("short", False)):
            i = pick(pol, long_)[0][0]
            n = rises_before(i) if pol == "rise" else falls_before(i)
            other = "FALL" if pol == "rise" else "RISE"
            t15.append((f"t15_a{pol[0]}_b{other[0].lower()}_{ctx}",
                        f".meas tran t15_a{pol[0]}_b{other[0].lower()}_{ctx} TRIG v(dsa) VAL=0 {pol.upper()}={n} "
                        f"TARG v(dsb) VAL=0 {other}={n}"))
    for pol in ("rise", "fall"):
        for par in (0, 1):
            for ctx, long_ in (("long", True), ("short", False)):
                c = [t for t in pick(pol, long_) if t[0] % 2 == par]
                i = c[0][0]
                n = rises_before(i) if pol == "rise" else falls_before(i)
                cpol = "RISE" if i % 2 == 0 else "FALL"
                cn = i // 2 + 1 if i % 2 == 0 else (i + 1) // 2
                nm = f"t16_d{pol[0]}_c{cpol[0].lower()}_{ctx}"
                t16.append((nm, f".meas tran {nm} TRIG v(dsa) VAL=0 {pol.upper()}={n} TARG v(csig) VAL=0 {cpol}={cn}"))
    return t15, t16


def window_gate(s):
    ph = "((time*1e12)%1000)"
    e = s + EYE_WIN_PS
    phase = f"({ph} ge {s})*({ph} lt {e})" if e <= UI_PS else f"(({ph} ge {s})+({ph} lt {e - UI_PS}))"
    return f"(time ge {T0_NS}e-9)*(time lt {T1_NS}e-9)*{phase}"


def meas(name, **kw):
    kw["name"] = name
    return kw


def measurements(kind):
    ch = kind == "ch"
    m = []
    lim = lambda **k: {"limits": k} if ch else {}
    pr = prbs7()
    n_edges = sum(1 for i in range(PERIOD) if pr[i] != pr[i - 1])  # cyclic transitions per period
    for lane, rx in (("a", "vdd_arx"), ("b", "vdd_brx")):
        x = f"(v(dout{lane})-0.5*v({rx}) gt 0)"
        n = "length(time)"
        gate = f"(time[1,{n}-1] ge {T0_NS}e-9)*(time[1,{n}-1] lt {T1_NS}e-9)"
        m.append(meas(f"t01_dout_edges_{lane}", spec_row="T-01", unit="count",
                      expr=f"mean(abs({x}[1,{n}-1]-{x}[0,{n}-2])*{gate})*({n}-1)",
                      **lim(min=n_edges - 0.5, max=n_edges + 0.5)))
    if ch:  # T-18 is CH only (test-configuration.md: L2 and L1 cannot observe an eye)
        wins = list(range(0, UI_PS, EYE_STEP_PS))
        for k, s in enumerate(wins):
            m.append(meas(f"eye_win_{k:02d}", unit="V", spec_row="T-18",
                          expr=f"vecmin(abs(v(rxa)-0.5*v(vdd_arx))+10*(1-{window_gate(s)}))"))
        for k in range(1, len(wins)):
            prev = "eye_win_00" if k == 1 else f"eye_mx_{k - 1:02d}"
            nm = "eye_h_best_v" if k == len(wins) - 1 else f"eye_mx_{k:02d}"
            m.append(meas(nm, unit="V", spec_row="T-18", expr=f"({prev}+eye_win_{k:02d}+abs({prev}-eye_win_{k:02d}))/2"))
        m.append(meas("t18_eye_windows_open", unit="count", spec_row="T-18",
                      expr="(" + "+".join(f"(eye_win_{k:02d} ge {EYE_H_V})" for k in range(len(wins))) + ")",
                      limits={"min": 1}))
        m.append(meas("t18_eye_height_ok_v", unit="V", spec_row="T-18", expr="eye_h_best_v",
                      limits={"min": EYE_H_V}))
    for lane, pin in PINS.items():
        rx = RX[lane]
        top, vd = f"vecmax(v({pin}))", f"vecmax(v({rx}))"
        m.append(meas(f"t09_over_{lane}", unit="ratio", spec_row="T-09", expr=f"({top}-{vd})/{vd}",
                      **({"limits": {"max": 0.25}})))
        m.append(meas(f"t09_under_{lane}", unit="ratio", spec_row="T-09", expr=f"(0-vecmin(v({pin})))/{vd}",
                      **({"limits": {"max": 0.25}})))
        for tag, sign in (("over", f"v({pin})-1.25*v({rx})"), ("under", f"-0.25*v({rx})-v({pin})")):
            m.append(meas(f"t09_dwell_{tag}_{lane}", unit="s", spec_row="T-09",
                          spice=f".meas tran t09_dwell_{tag}_{lane} INTEG par('u({sign})') FROM={T0_NS}n TO={T1_NS}n",
                          limits={"max": 0.4e-9}))
    p = lambda a: f"v({a})*i({a})"
    e = (f"-({p('vdd_atx')}+{p('vdd_arx')}+({p('vdd_ctx')}+{p('vdd_crx')})/{N_WIRES})/{PERIOD}")
    m.append(meas("t26_energy_per_bit_simulated_j", unit="J", spec_row="T-26",
                  spice=f".meas tran t26_energy_per_bit_simulated_j INTEG par('{e}') FROM={T0_NS}n TO={T1_NS}n",
                  **lim(max=1e-12)))
    for nm, srcs in (("e_lane_a_tx_j", ["vdd_atx"]), ("e_lane_a_rx_j", ["vdd_arx"]),
                     ("e_clock_lane_j", ["vdd_ctx", "vdd_crx"])):
        pw = "+".join(p(s) for s in srcs)
        m.append(meas(nm, unit="J", spec_row="T-26",
                      spice=f".meas tran {nm} INTEG par('-({pw})') FROM={T0_NS}n TO={T1_NS}n"))
    if ch:  # T-15 / T-16: single-instance half only; the array and Monte Carlo half is #44
        t15, t16 = skew_pairs()
        for nm, card in t15:
            m.append(meas(nm, unit="s", spec_row="T-15", spice=card, limits={"min": -0.06e-9, "max": 0.06e-9}))
        for nm, card in t16:
            m.append(meas(nm, unit="s", spec_row="T-16", spice=card,
                          limits={"min": 0.5e-9 - 0.03e-9, "max": 0.5e-9 + 0.03e-9}))
    return m


def request(kind):
    sections = [{"name": c, "sections": [c, {"lib": MODELS + "cornerRES.lib", "section": r},
                                         {"lib": MODELS + "cornerDIO.lib", "section": d}]}
                for c, (r, d) in PROCESS.items()]
    return {
        "engine": "ngspice",
        "models": {"pdk": "ihp-sg13g2", "lib": MODELS + "cornerMOSlv.lib"},
        "netlist": f"tb_{kind}.cir",
        "backend": "batch",
        "corners": {"process": sections,
                    "supply_v": {s: [1.08, 1.2, 1.32] for s in SUPPLIES},
                    "temperature_c": [-40, 27, 125]},
        "analysis": {"kind": "tran", "args": f"2p {T1_NS}n 0 5p"},
        "measurements": measurements(kind),
        # fleet runner is klt 0.7.0 and rejects the 0.8.0 pinned client without this (see README)
        "batch": {"runner_version_check": "warn"},
        # measured ~8 s of ngspice per ns of stimulus at mos_tt/1.2 V/27 C: ~1100 s per corner
        "options": {"osdi_preload": [f"$PDK_ROOT/ihp-sg13g2/libs.tech/ngspice/osdi/{o}.osdi" for o in OSDI],
                    "timeout_s": 2400},
    }


def control_request():
    """Bench positive control: CH netlist with the output-PMOS-fixed TX copy, one corner (tt, 1.20 V, 27 C)."""
    r = request("ch")
    r["netlist"] = "tb_ctl_ch.cir"
    r["corners"] = {"process": [c for c in r["corners"]["process"] if c["name"] == "mos_tt"],
                    "supply_v": {s: [1.2] for s in SUPPLIES}, "temperature_c": [27]}
    return r


def outputs():
    o = {"prbs7_stim.inc": stim_include()}
    for k in ("ch", "tc"):
        o[f"request_{k}_1g.json"] = json.dumps(request(k), indent=2) + "\n"
    o["request_ctl_ch_tt.json"] = json.dumps(control_request(), indent=2) + "\n"
    return o


def main(argv):
    stale = []
    for name, text in outputs().items():
        path = HERE / name
        if "--check" in argv:
            if not path.exists() or path.read_text() != text:
                stale.append(name)
        else:
            path.write_text(text)
    if stale:
        print("stale generated files: " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
