#!/usr/bin/env python3
"""Generate the T-19 (RX capture window) single-transient benches: tb_t19.cir and tb_t19_ctl.cir.

Stdlib only. `python3 -I sim/mc/capture_window/gen_t19.py [--check]`.

Subject: design/aib_rx_data.spice (input stage, as drawn) driving D of the PDK flop
sg13g2_dfrbpq_1 (vendored verbatim, sg13g2_dfrbpq_1.inc). A netlist body cannot carry a
.control loop, so the aperture is found by a swept-offset transient instead of a bisection:
2*K cycles of PERIOD_PS; the data edge moves by DELTA_PS per cycle across the clock edge.

Setup phase (cycles 0..K-1): data rises at clock + x_k, x_k = -XM + k*DELTA (early to late),
falls at a fixed late time. The flop captures 1 until the data is too late; Q falls at the
first failing cycle. xr is a staircase holding x_k (1 V = 1 ns), so FIND v(xr) at that fall
reads the first failing x.
Hold phase (cycles K..2K-1): data is high from early in the cycle and falls at clock + y_j,
y_j = -XM + j*DELTA. Q is 0 until the data falls late enough; Q rises at the first
capturing cycle, and FIND v(yr) at that rise reads the first capturing y.
Setup/hold are referred to the 50 % crossing of D (the input-stage output): the pad-to-D
delays dr (rising) and df (falling) are measured on the first hold cycle, away from the clock.
  setup = -(xs - DELTA/2 + dr),  hold = ys - DELTA/2 + df,  aperture = setup + hold.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent.parent))
import gen_common  # noqa: E402  (the one write-or-check implementation)

PERIOD_PS = 2000
DELTA_PS = 10
XLO_PS = -400        # sweep window around the clock edge: data edges at clock + XLO .. XHI (setup
XHI_PS = 100         # and hold both sit before the edge once the input stage delay is included)
CLK_PS = 1000        # clock rising 50 % crossing, local to a cycle
RISE_PS = 100        # edge ramp (crossing +- RISE/2), as the PRBS bench
SETUP_FALL_PS = 1600  # data fall crossing in the setup phase
HOLD_RISE_PS = 300    # data rise crossing in the hold phase
CLK_FALL_PS = 1900
CTL_CLK_RAMP_PS = 1500 # negative control: slow forwarded-clock edge at the flop
K = (XHI_PS - XLO_PS) // DELTA_PS + 1
T_SETUP_END_PS = K * PERIOD_PS
T_END_PS = 2 * K * PERIOD_PS


def ns(ps: float) -> str:
    return f"{ps / 1000:.4f}n"


def pwl(points: list) -> str:
    """Collapse to a PWL card body; points are (t_ps, value)."""
    return " ".join(f"{ns(t)} {v:g}" for t, v in points)


def edge(points: list, cross_ps: float, to: float, ramp_ps: float = RISE_PS) -> None:
    points.append((cross_ps - ramp_ps / 2, points[-1][1]))
    points.append((cross_ps + ramp_ps / 2, to))


def stimuli(clk_ramp_ps: float = RISE_PS) -> dict:
    pad = [(0.0, 0)]
    clk = [(0.0, 0)]
    xr = [(0.0, XLO_PS / 1000)]
    yr = [(0.0, XLO_PS / 1000)]
    for c in range(2 * K):
        base = c * PERIOD_PS
        if c < K:
            x = XLO_PS + c * DELTA_PS
            edge(pad, base + CLK_PS + x, 1)
            edge(pad, base + SETUP_FALL_PS, 0)
        else:
            y = XLO_PS + (c - K) * DELTA_PS
            edge(pad, base + HOLD_RISE_PS, 1)
            edge(pad, base + CLK_PS + y, 0)
        edge(clk, base + CLK_PS, 1, clk_ramp_ps)
        edge(clk, base + CLK_FALL_PS, 0)
        # staircases step at the cycle start, 1 ps ramps, well away from every edge
        # (hold the previous level to the cycle start: PWL interpolates between points)
        if c < K:
            if c:
                xr.append((base, xr[-1][1]))
            xr.append((base + 1, (XLO_PS + c * DELTA_PS) / 1000))
        else:
            yr.append((base, yr[-1][1]))
            yr.append((base + 1, (XLO_PS + (c - K) * DELTA_PS) / 1000))
    return {"pad": pad, "clk": clk, "xr": xr, "yr": yr}


def netlist(ctl: bool) -> str:
    s = stimuli(CTL_CLK_RAMP_PS if ctl else RISE_PS)
    name = "tb_t19_ctl.cir" if ctl else "tb_t19.cir"
    out = [
        f"* {name} -- T-19 receiver capture window: aib_rx_data input stage -> sg13g2_dfrbpq_1 (generated by gen_t19.py)",
        "* Swept-offset single transient: setup phase then hold phase; see gen_t19.py for the method.",
        "* Supply: one source `vdd_rx` (VDDIO = flop VDD), swept by corners.supply_v.",
        ".include ../../../design/aib_rx_data.spice",
        ".include sg13g2_dfrbpq_1.inc",
        "Vdd_rx vdd_rx 0 DC 1.2",
        f"Vpn pn 0 dc 0 pwl({pwl(s['pad'])})",
        f"Vcn cn 0 dc 0 pwl({pwl(s['clk'])})",
        f"Vxr xr 0 dc 0 pwl({pwl(s['xr'])})",
        f"Vyr yr 0 dc 0 pwl({pwl(s['yr'])})",
        "Bpad pad 0 V = v(pn)*v(vdd_rx)",
        "Bclk clk 0 V = v(cn)*v(vdd_rx)",
        "Xrx pad d vdd_rx 0 aib_rx_data",
        "Xff q clk d vff vff 0 sg13g2_dfrbpq_1",
        "Cq q 0 5f",
    ]
    if ctl:
        out += [f"* Negative control (not design evidence): the clock edge at the flop ramps over {CTL_CLK_RAMP_PS} ps",
                "* instead of 100 ps, which widens the capture aperture; everything else is unchanged."]
    out += ["Vff vff vdd_rx DC 0"]
    out += [
        "* mid-rail-referenced copies so every WHEN/TRIG uses VAL=0 at any supply",
        "Bph padh 0 V = v(pad) - 0.5*v(vdd_rx)",
        "Bdh dh 0 V = v(d) - 0.5*v(vdd_rx)",
        "Bqh qh 0 V = v(q) - 0.5*v(vff)",
        ".end",
    ]
    return "\n".join(out) + "\n"


def steps() -> list:
    """Measurement cards for the request (kept here so the netlist and the cards share constants)."""
    hold0 = T_SETUP_END_PS
    return {
        "xs": f".meas tran xs FIND v(xr) WHEN v(qh)=0 FALL=1 FROM={ns(1500)} TO={ns(T_SETUP_END_PS)}",
        "ys": f".meas tran ys FIND v(yr) WHEN v(qh)=0 RISE=1 FROM={ns(T_SETUP_END_PS)} TO={ns(T_END_PS)}",
        "dr": f".meas tran dr TRIG v(padh) VAL=0 RISE=1 FROM={ns(hold0 + 200)} TO={ns(hold0 + 700)} "
              f"TARG v(dh) VAL=0 RISE=1",
        "df": f".meas tran df TRIG v(padh) VAL=0 FALL=1 FROM={ns(hold0 + 500)} TO={ns(hold0 + PERIOD_PS)} "
              f"TARG v(dh) VAL=0 FALL=1",
    }


def setup_hold_ps(xs: float, ys: float, dr: float, df: float) -> tuple:
    """(setup_ps, hold_ps, aperture_ps) from the four measurements: xs, ys in V (1 V = 1 ns,
    the first failing / first capturing pad offset), dr, df in s. Mirrors the `expr` strings
    in gen_mc.py (the test evaluates both on the same numbers)."""
    half = DELTA_PS / 2000
    setup = -((xs - half) * 1000 + dr * 1e12)
    hold = (ys - half) * 1000 + df * 1e12
    return setup, hold, setup + hold


def outputs() -> dict:
    return {"tb_t19.cir": netlist(False), "tb_t19_ctl.cir": netlist(True)}


def main() -> int:
    return gen_common.write_or_check(outputs(), base=HERE,
                                     description=__doc__.splitlines()[0])


if __name__ == "__main__":
    sys.exit(main())
