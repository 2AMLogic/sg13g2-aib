#!/usr/bin/env python3
"""Per-corner reading of the graded Monte Carlo records (T-10, T-15, T-16).

Stdlib only. `python3 -I sim/mc/gen_per_corner.py [--check]` writes (or checks)
`per_corner.md`: one table per graded STAT row, one row per PVT-FULL corner, read from
the committed `report.json.gz` of the record. `klt yield` pools the 45 corners into one
distribution ("a worst-case envelope rather than a distribution anyone sampled",
sim/mc/README.md), so the pooled record cannot say which corners carry the out-of-limit
draws -- the question any fix has to answer first, and still the reading wanted from a
passing row (where its binding corner sits). Every per-corner column that the record
does carry (`by_corner` mean and sigma) is cross-checked, and the two it does not
carry (out-of-limit count, margin-ranked worst draw) are derived from the per-draw
entries, the same margin ranking `klt`'s `worst_case` uses.

Nothing under `records/` is read or written but the report itself; a new simulation is
out of scope (issue #269; the T-15 / T-16 re-run itself was #385).
"""

import gzip
import json
import math
import statistics
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
import gen_common  # noqa: E402  (write_or_check)

# The graded STAT rows (sim/mc/README.md). T-10 still fails on its 2026-11-08 record
# (#386 tracks a re-run on the current cells); T-15 / T-16 are the 2026-11-20 re-runs of
# #385, which pass. T-19 passes and is out of scope; T-13 / T-14 have no record on
# main (#136).
RECORDS = [
    ("T-10 receiver threshold", "records/20261108T035315Z-t10"),
    ("T-15 RX data-to-data skew (CH)", "records/20261120T202400Z-t15"),
    ("T-16 RX data-to-clock skew (CH)", "records/20261120T202400Z-t16"),
]

# The record's own pooled and per-corner figures reproduce bit-for-bit from the
# per-draw entries with statistics.fmean/stdev; the tolerance only leaves float
# slack for a summation-order change, so even a pstdev/n-2 slip (a 4e-6 relative
# error on these records) fails loudly.
REL_TOL = 1e-12

PREAMBLE = """\
# Per-corner Monte Carlo reading: T-10, T-15, T-16

Generated by `sim/mc/gen_per_corner.py` from the committed `report.json.gz` of each record
(`python3 -I sim/mc/gen_per_corner.py`; `--check` in `scripts/ci/check_local.sh` fails when
stale). Do not edit by hand.

`klt yield` pools the 45 PVT-FULL corners of each graded STAT row into one distribution
("a worst-case envelope rather than a distribution anyone sampled", `sim/mc/README.md`), so
a pooled record cannot say which corners carry the out-of-limit draws. For every
corner this document tables the draw count, the per-corner mean and sample sigma (n-1, the
convention `klt` reports, pooled and in `by_corner`), the margin-ranked worst draw (the
same definition `klt`'s `worst_case` uses) and the count of draws outside the row's limits.
Every draw is explicitly labelled with its corner in the record (`corner_id` plus the typed
`process` / `supply_v` / `temperature_c` and `monte_carlo.sample_index`), so no corner is
inferred from sample order. The generator cross-checks each table's totals against the
record's own pooled `monte_carlo` block and `failed` count, and every per-corner mean and
sigma against its `by_corner` entry; a mismatch fails the script.

T-15 and T-16 are the 2026-11-20 re-runs of #385 on the cells of `main` at `7a7c5b9`
(after the TX predriver resize of #164 and the `aib_pad_esd` `XResd` shortening of #332);
both pass the 7-sigma gate pooled, so their tables say where the binding corner sits rather
than which corners fail. T-10 remains the failing 2026-11-08 record (#386 tracks its
re-run).

"""


def supply_mv(draw) -> float:
    """The one supply value a draw's `supply_v` carries, in volts.

    T-10 records a single rail; T-15 / T-16 record the six `vdd_*` rails, which move in
    lockstep on the grid (`sim/mc/README.md`). Rails that do not collapse to one value
    are an error, not something to average: the corner label would be a lie.
    """
    values = sorted(set(draw["supply_v"].values())) if isinstance(draw["supply_v"], dict) else [draw["supply_v"]]
    if len(values) != 1:
        raise SystemExit(f"supply rails do not collapse to one value, cannot label the corner: {draw['supply_v']}")
    return values[0]


def corner_label(draw) -> str:
    """`sf/1.320V/125C`, from the typed fields, not by parsing `corner_id` -- whose supply
    part has two shapes across these records (`1.080V` vs six `vdd_*=<n>V` rails)."""
    return f'{draw["process"]}/{supply_mv(draw):.3f}V/{draw["temperature_c"]}C'


def corner_key(corner_id: str) -> str:
    """The per-corner id a draw's `corner_id` carries: the id minus its `/mc<N>` suffix,
    the same key the record's `by_corner` block is keyed on."""
    return corner_id.rsplit("/mc", 1)[0]


def check_corner_id(draw):
    """The typed fields and the `corner_id` must agree, so the two id shapes cannot drift
    apart from the fields the label is built from."""
    key = corner_key(draw["corner_id"])
    process, temp = key.split("/")[0], key.rsplit("/", 1)[1]
    if process != draw["process"] or temp != f'{draw["temperature_c"]}C':
        raise SystemExit(f'corner_id {draw["corner_id"]!r} disagrees with its typed fields '
                         f'(process {draw["process"]!r}, temperature {draw["temperature_c"]}C)')


def check_close(mine, ref, what):
    if not math.isclose(mine, ref, rel_tol=REL_TOL):
        raise SystemExit(f"{what}: computed {mine!r} but the record carries {ref!r}")


def limits_text(limits, unit) -> str:
    lo, hi = limits.get("min"), limits.get("max")
    if lo is not None and hi is not None and lo == -hi:
        return f"+-{-lo:g} {unit}"
    if lo is not None and hi is not None:
        return f"[{lo:g}, {hi:g}] {unit}"
    return (f"<= {hi:g} {unit}" if lo is None else f">= {lo:g} {unit}")


def graded_section(title, rel) -> str:
    """The markdown section for one record: one table per graded measurement."""
    path = HERE / rel / "report.json.gz"
    with gzip.open(path, "rt") as f:
        report = json.load(f)
    graded = [m for m in report["measurements"] if m["limits"] is not None]
    if not graded:
        raise SystemExit(f"{rel}: no graded measurement to table")
    parts = []
    for meas in graded:
        parts.append(measure_section(title, rel, report, meas))
    return "".join(parts)


def measure_section(title, rel, report, meas) -> str:
    name, unit, mc = meas["name"], meas["unit"], meas["monte_carlo"]
    by_corner = {b["corner_id"]: b for b in mc["by_corner"]}
    groups = {}
    for draw in report["corners"]:
        check_corner_id(draw)
        key = corner_key(draw["corner_id"])
        group = groups.setdefault(key, {"label": corner_label(draw), "vals": [], "outs": 0,
                                        "worst": None})
        found = [m for m in draw["measurements"] if m["name"] == name]
        if len(found) != 1 or found[0].get("value") is None or found[0].get("margin") is None:
            raise SystemExit(f'{rel}: draw {draw["corner_id"]!r} carries no numeric {name!r} '
                             f"with a margin; per-corner reading would be silent about it")
        value, margin = found[0]["value"], found[0]["margin"]
        group["vals"].append(value)
        if margin < 0:
            group["outs"] += 1
        if group["worst"] is None or margin < group["worst"][1]:
            group["worst"] = (value, margin)

    if len(groups) != len(by_corner):
        raise SystemExit(f"{rel}: {len(groups)} distinct corners but the record's by_corner "
                         f"block carries {len(by_corner)}")
    labels = {g["label"] for g in groups.values()}
    if len(labels) != len(groups):
        raise SystemExit(f"{rel}: {len(groups)} corners but {len(labels)} distinct labels; "
                         "the typed fields do not separate the corners")
    if set(groups) != set(by_corner):
        raise SystemExit(f"{rel}: per-draw corner keys and by_corner keys differ")

    rows = sorted(groups.values(), key=lambda g: (-g["outs"], g["worst"][1], g["label"]))
    for key, g in groups.items():
        b = by_corner[key]
        if len(g["vals"]) != b["n"]:
            raise SystemExit(f'{g["label"]}: {len(g["vals"])} draws but by_corner carries n={b["n"]}')
        check_close(statistics.fmean(g["vals"]), b["mean"], f'{g["label"]} mean vs by_corner')
        check_close(statistics.stdev(g["vals"]), b["stddev"], f'{g["label"]} sigma vs by_corner')

    all_vals = [v for g in groups.values() for v in g["vals"]]
    n, outs = len(all_vals), sum(g["outs"] for g in groups.values())
    mean, sigma = statistics.fmean(all_vals), statistics.stdev(all_vals)
    check_close(mean, mc["mean"], f"{name} pooled mean")
    check_close(sigma, mc["stddev"], f"{name} pooled sigma")
    if n != mc["n"] or outs != report["failed"]:
        raise SystemExit(f"{name}: {n} draws / {outs} outside limits but the record carries "
                         f'n={mc["n"]} / failed={report["failed"]}')
    binding = min(groups.values(), key=lambda g: g["worst"][1])
    wc = meas["worst_case"]
    if corner_key(wc["corner_id"]) not in groups or \
            groups[corner_key(wc["corner_id"])] is not binding:
        raise SystemExit(f"{name}: margin-ranked worst draw sits at {binding['label']} but the "
                         f'record\'s worst_case names {wc["corner_id"]!r}')
    check_close(binding["worst"][0], wc["value"], f"{name} worst draw")

    per_corner = {len(g["vals"]) for g in groups.values()}
    shape = (f"{len(groups)} corners x {per_corner.pop()} draws" if len(per_corner) == 1
             else f"{n} draws, non-uniform per corner")
    holding = sum(1 for g in groups.values() if g["outs"])
    head = (f"Record `{rel}/`: {shape}, {outs} outside the limits ({100 * outs / n:.1f} %), "
            f"pooled mean {mean:.3f} {unit}, pooled sigma (n-1) {sigma:.3f} {unit}.\n"
            f"**{holding} of {len(groups)} corners hold out-of-limit draws; the binding corner "
            f"is `{binding['label']}`** (holder of the margin-ranked worst draw).")
    lines = [
        f"## {title} -- `{name}` ({unit}), limits {limits_text(meas['limits'], unit)}",
        "",
        head,
        "",
        f"| Corner | Draws | Outside limits | Mean ({unit}) | Sigma ({unit}, n-1) | "
        f"Worst draw ({unit}) |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for g in rows:
        lines.append(f"| {g['label']} | {len(g['vals'])} | {g['outs']} | "
                     f"{statistics.fmean(g['vals']):.3f} | {statistics.stdev(g['vals']):.3f} | "
                     f"{g['worst'][0]:.3f} |")
    return "\n".join(lines) + "\n\n"


def outputs() -> dict:
    """path -> text for every file this script writes."""
    body = PREAMBLE + "".join(graded_section(title, rel) for title, rel in RECORDS)
    return {HERE / "per_corner.md": body}


def main() -> int:
    return gen_common.write_or_check(outputs(), description=__doc__.splitlines()[0])


if __name__ == "__main__":
    sys.exit(main())
