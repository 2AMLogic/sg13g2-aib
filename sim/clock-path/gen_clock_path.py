#!/usr/bin/env python3
"""Generate the clock-path stimulus include and the `klt sim` request.

Stdlib only. Usage:
  python3 -I sim/clock-path/gen_clock_path.py          # write the generated files
  python3 -I sim/clock-path/gen_clock_path.py --check  # exit 1 if they are stale

Generated: clock_stim.inc, request.json.

Timing: UI 1000 ps (1 Gb/s DDR, 500 MHz forwarded clock, period 2 ns). The clock is an ideal
complementary 50 % pair (equal rise and fall ramps), so the measured duty-cycle distortion is
what the TX clock path adds. Data toggles every UI with its edges at k UI; the clock edges are at
(k + 0.5) UI (center aligned, nominal 0.5 UI).
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
UI_PS = 1000
TR_PS = 100
NUI = 24                  # stimulus length in UI (12 clock periods)
N = 6                     # measured edge: the N-th crossing of each polarity (settled, > 10 ns)
SUPPLIES = ["vdd_tx", "vdd_rx"]
OSDI = ["psp103", "psp103_nqs", "r3_cmc", "mosvar"]
PROCESS = {"mos_tt": ("res_typ", "dio_tt"), "mos_ss": ("res_wcs", "dio_ss"),
           "mos_ff": ("res_bcs", "dio_ff"), "mos_sf": ("res_typ", "dio_tt"),
           "mos_fs": ("res_typ", "dio_tt")}
MODELS = "libs.tech/ngspice/models/"


def pwl(points):
    return " ".join(f"{t * 1e-12:.6g} {v}" for t, v in points)


def level_pwl(edges, init=0):
    """edges: [(start_ps, level)]; each edge is a TR-long ramp starting at start_ps."""
    pts, cur = [(0, init)], init
    for t, v in edges:
        pts += [(t, cur), (t + TR_PS, v)]
        cur = v
    pts.append((NUI * UI_PS, cur))
    return pts


def stim_include():
    clk = [(k * UI_PS + UI_PS // 2, 1 if k % 2 == 0 else 0) for k in range(NUI)]
    dat = [(k * UI_PS, 1 if k % 2 == 0 else 0) for k in range(NUI)]
    lines = ["* clock_stim.inc -- GENERATED by gen_clock_path.py; do not edit.",
             f"* UI {UI_PS} ps, ramp {TR_PS} ps, {NUI} UI. Normalised 0..1 levels; tb_clock_path.cir scales them.",
             f"Vpc pc 0 dc 0 pwl({pwl(level_pwl(clk))})",
             f"Vpd pd_ 0 dc 0 pwl({pwl(level_pwl(dat))})"]
    return "\n".join(lines) + "\n"


def m(name, unit, row, spice=None, expr=None, **limits):
    d = {"name": name, "unit": unit, "spec_row": row}
    if spice:
        d["spice"] = f".meas tran {name} {spice}"
    if expr:
        d["expr"] = expr
    if limits:
        d["limits"] = limits
    return d


def measurements():
    out = []
    # T-17: duty of the forwarded clock at the TX output (cell pad node), high time / period - 0.5
    for p in ("c", "cb"):
        v = f"v(dt{p})"
        fall = N if p == "c" else N + 1   # clkb starts high: its high time is rise N to fall N + 1
        out += [m(f"t17_hi_{p}", "s", "T-17", f"TRIG {v} VAL=0 RISE={N} TARG {v} VAL=0 FALL={fall}"),
                m(f"t17_per_{p}", "s", "T-17", f"TRIG {v} VAL=0 RISE={N} TARG {v} VAL=0 RISE={N + 1}"),
                m(f"t17_dcd_{p}", "ratio", "T-17", f"param='t17_hi_{p}/t17_per_{p}-0.5'", min=-0.03, max=0.03)]
    # T-04: clk/clkb crossing at the RX pins and at the RX outputs; report-only (no numeric bound in spec)
    for tag, d in (("pin", "dxp"), ("out", "dxo")):
        cs = "csp" if tag == "pin" else "cso"
        for pol in ("RISE", "FALL"):
            out.append(m(f"t04_xlevel_{tag}_{pol[0].lower()}_v", "V", "T-04",
                         f"FIND v({d}) WHEN v({cs})=0 {pol}={N}"))
    out.append(m("t04_latency_s", "s", "T-04", "TRIG v(csd) VAL=0 RISE=%d TARG v(cso) VAL=0 RISE=%d" % (N, N)))
    # T-02 (SIM half): data edge to the forwarded clock's edges at the RX outputs; report-only
    for nm, tr, ta in (("t02_dr_cr", "v(ddo0) VAL=0 RISE", "v(dxo) VAL=0 RISE"),
                       ("t02_df_cf", "v(ddo0) VAL=0 FALL", "v(dxo) VAL=0 FALL"),
                       ("t02_cr_df", "v(dxo) VAL=0 RISE", "v(ddo0) VAL=0 FALL"),
                       ("t02_cf_dr", "v(dxo) VAL=0 FALL", "v(ddo0) VAL=0 RISE")):
        out.append(m(nm, "s", "T-02", f"TRIG {tr}={N} TARG {ta}={N + (1 if nm == 't02_cf_dr' else 0)}"))
    return out


def request():
    sections = [{"name": c, "sections": [c, {"lib": MODELS + "cornerRES.lib", "section": r},
                                         {"lib": MODELS + "cornerDIO.lib", "section": d}]}
                for c, (r, d) in PROCESS.items()]
    return {
        "engine": "ngspice",
        "models": {"pdk": "ihp-sg13g2", "lib": MODELS + "cornerMOSlv.lib"},
        "netlist": "tb_clock_path.cir",
        "backend": "batch",
        "corners": {"process": sections,
                    "supply_v": {s: [1.08, 1.2, 1.32] for s in SUPPLIES},
                    "temperature_c": [-40, 27, 125]},
        "analysis": {"kind": "tran", "args": f"2p {NUI}n 0 5p"},
        "measurements": measurements(),
        "batch": {"runner_version_check": "warn"},
        # ~4 s of ngspice per corner alone, but ~160 s per unit in a 3-unit fleet job (measured); 3 units x 1100 s fits the 3600 s job ceiling
        "options": {"osdi_preload": [f"$PDK_ROOT/ihp-sg13g2/libs.tech/ngspice/osdi/{o}.osdi" for o in OSDI],
                    "timeout_s": 1100},
    }


def outputs():
    return {"clock_stim.inc": stim_include(), "request.json": json.dumps(request(), indent=2) + "\n"}


def main(argv):
    stale = []
    for name, text in outputs().items():
        path = HERE / name
        if "--check" in argv:
            if not path.exists() or path.read_text() != text:
                stale.append(name)
        else:
            path.write_text(text)
    if stale:
        print("stale generated files: " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
