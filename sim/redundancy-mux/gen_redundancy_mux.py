#!/usr/bin/env python3
"""Generate the redundancy-mux stimulus include and the `klt sim` request (T-05 SIM leg).

Stdlib only. Usage:
  python3 -I sim/redundancy-mux/gen_redundancy_mux.py          # write the generated files
  python3 -I sim/redundancy-mux/gen_redundancy_mux.py --check  # exit 1 if they are stale

Generated: redundancy_mux_stim.inc, request.json, request_tt.json.

Timing: UI 1000 ps (1 Gb/s DDR, 500 MHz forwarded clock, period 2 ns). `clk` is the
serializer's select input and the one common reference every lane's delay is measured
from; it is an ideal 50 % square wave with equal rise and fall ramps, so it contributes
nothing of its own to a lane-to-lane difference. With the serializer's two inputs held
at static complementary levels (o_p = 1, o_n = 0) each lane's serialized output is `~clk`
-- a 1010 pattern toggling once per UI, which is what a delay and slew measurement wants.

Nothing in this request carries `limits`. `spec/target-spec.md` T-05 states no bound for
this leg and DR-0023 does not invent one: every measurement is reported, exactly as the
T-02 and T-04 measurements of the clock-path family are. A bench self-check limit on the
negative control was considered and rejected -- it would make a report-only row look
graded to anyone who later cited this envelope.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))
import pvt_full  # noqa: E402  (the one PVT-FULL corner-bundle definition)

UI_PS = 1000
TR_PS = 100
T0_PS = 500               # first clk edge; keeps the DC operating point away from a ramp
NUI = 24                  # stimulus length in UI (12 clock periods)
N = 6                     # measured edge: the N-th crossing of each polarity (settled, > 10 ns)
SUPPLIES = ["vdd_tx"]

# The four lanes of tb_redundancy_mux.cir: (tag, pad probe, serializer probe, |i| probe).
LANES = (("b", "hb", "hbs", "qb", "bs10", "bs90"),
         ("c", "hc", "hcs", "qc", "cs10", "cs90"),
         ("m0", "hm0", "hm0s", "qm0", "m0s10", "m0s90"),
         ("m1", "hm1", "hm1s", "qm1", "m1s10", "m1s90"))


def clk_crossing_ps(n, rise=True):
    """Mid-rail crossing time of the n-th clk rise (or fall), stimulus time base."""
    edge = T0_PS + (2 * (n - 1) + (0 if rise else 1)) * UI_PS
    return edge + TR_PS // 2


def charge_window_ps():
    """One whole clk period around the N-th pair of serializer edges.

    The window holds exactly one rise and one fall of the serializer output, so the
    integral of |i| through it is 2*Ceff*VDD whatever the endpoints are doing -- the
    window needs no settled endpoint and no per-corner placement.
    """
    start = clk_crossing_ps(N, rise=True) - UI_PS // 2
    return start, start + 2 * UI_PS


def pwl(points):
    return " ".join(f"{t * 1e-12:.6g} {v}" for t, v in points)


def level_pwl(edges, init=0):
    """edges: [(start_ps, level)]; each edge is a TR-long ramp starting at start_ps."""
    pts, cur = [(0, init)], init
    for t, v in edges:
        pts += [(t, cur), (t + TR_PS, v)]
        cur = v
    pts.append((NUI * UI_PS, cur))
    return pts


def stim_include():
    edges = [(T0_PS + k * UI_PS, 1 if k % 2 == 0 else 0) for k in range(NUI - 1)]
    lines = ["* redundancy_mux_stim.inc -- GENERATED by gen_redundancy_mux.py; do not edit.",
             f"* Serializer select: ideal 50 % {1e6 / (2 * UI_PS):.0f} MHz square, ramp {TR_PS} ps, "
             f"first edge {T0_PS} ps, {NUI} UI total.",
             "* Normalised 0..1 level; tb_redundancy_mux.cir scales it by the swept supply.",
             f"Vpclk pclk 0 dc 0 pwl({pwl(level_pwl(edges))})"]
    return "\n".join(lines) + "\n"


def m(name, unit, spice, row="T-05"):
    return {"name": name, "unit": unit, "spec_row": row, "spice": f".meas tran {name} {spice}"}


def param(name, unit, expr, row="T-05"):
    return m(name, unit, f"param='{expr}'", row)


def measurements():
    out = [m("t05_vdd_v", "V", f"FIND v(vdd_tx) AT={clk_crossing_ps(1) * 1e-12:.6g}")]
    q_from, q_to = charge_window_ps()
    # --- per lane, raw -----------------------------------------------------------------
    # The serializer output is ~clk, so a clk FALL produces the lane's RISE and vice versa.
    for tag, pad, ser, q, p10, p90 in LANES:
        out += [
            m(f"t05_{tag}_dpr_s", "s", f"TRIG v(hclk) VAL=0 FALL={N} TARG v({pad}) VAL=0 RISE={N}"),
            m(f"t05_{tag}_dpf_s", "s", f"TRIG v(hclk) VAL=0 RISE={N} TARG v({pad}) VAL=0 FALL={N}"),
            m(f"t05_{tag}_dsr_s", "s", f"TRIG v(hclk) VAL=0 FALL={N} TARG v({ser}) VAL=0 RISE={N}"),
            m(f"t05_{tag}_dsf_s", "s", f"TRIG v(hclk) VAL=0 RISE={N} TARG v({ser}) VAL=0 FALL={N}"),
            m(f"t05_{tag}_tr_s", "s", f"TRIG v({p10}) VAL=0 RISE={N} TARG v({p90}) VAL=0 RISE={N}"),
            m(f"t05_{tag}_tf_s", "s", f"TRIG v({p90}) VAL=0 FALL={N} TARG v({p10}) VAL=0 FALL={N}"),
            m(f"t05_{tag}_q_c", "C", f"INTEG v({q}) FROM={q_from * 1e-12:.6g} TO={q_to * 1e-12:.6g}"),
            param(f"t05_{tag}_cl_f", "F", f"t05_{tag}_q_c/(2*t05_vdd_v)"),
        ]
    # --- the three terms the row's "added load/delay" names -----------------------------
    # 1. common added delay: every data lane gains one remap stage, the clock lane does not,
    #    so this is a data-to-clock offset and reports into T-20 (#177, #194).
    out += [param("t05_add_r_s", "s", "t05_m0_dpr_s-t05_b_dpr_s"),
            param("t05_add_f_s", "s", "t05_m0_dpf_s-t05_b_dpf_s"),
            param("t05_add1_r_s", "s", "t05_m1_dpr_s-t05_b_dpr_s"),
            param("t05_add1_f_s", "s", "t05_m1_dpf_s-t05_b_dpf_s")]
    # 2. select-dependent delay: in a repaired direction, wires below `pos` take A0 and wires
    #    at or above it take A1, so any A1-A0 difference is lane-to-lane skew (T-13, #136).
    out += [param("t05_sel_r_s", "s", "t05_m1_dpr_s-t05_m0_dpr_s"),
            param("t05_sel_f_s", "s", "t05_m1_dpf_s-t05_m0_dpf_s")]
    # 3. added load on the serializer output: two remap inputs instead of one DIN. Split the
    #    added delay into the load half (seen at the serializer output) and the stage half.
    out += [param("t05_load_r_s", "s", "t05_m0_dsr_s-t05_b_dsr_s"),
            param("t05_load_f_s", "s", "t05_m0_dsf_s-t05_b_dsf_s"),
            param("t05_stage_r_s", "s", "t05_add_r_s-t05_load_r_s"),
            param("t05_stage_f_s", "s", "t05_add_f_s-t05_load_f_s"),
            param("t05_dtr_s", "s", "t05_m0_tr_s-t05_b_tr_s"),
            param("t05_dtf_s", "s", "t05_m0_tf_s-t05_b_tf_s"),
            param("t05_dcl_f", "F", "t05_m0_cl_f-t05_b_cl_f")]
    # --- negative control: lane c is lane b built a second time, i.e. the remap stage
    # --- shorted out. It must reproduce the baseline; it is the noise floor the three
    # --- terms above are read against, and it claims nothing about the design.
    out += [param("t05_ctl_r_s", "s", "t05_c_dpr_s-t05_b_dpr_s"),
            param("t05_ctl_f_s", "s", "t05_c_dpf_s-t05_b_dpf_s"),
            param("t05_ctl_cl_f", "F", "t05_c_cl_f-t05_b_cl_f")]
    return out


def request():
    return {
        "engine": "ngspice",
        "models": {"pdk": "ihp-sg13g2", "lib": pvt_full.LIB_MOS},
        "netlist": "tb_redundancy_mux.cir",
        "backend": "batch",
        "corners": pvt_full.corners(SUPPLIES),
        "analysis": {"kind": "tran", "args": f"2p {NUI}n 0 5p"},
        "measurements": measurements(),
        "batch": {"runner_version_check": "warn", "capacity_wait_s": 600},
        # ~13 s of ngspice per corner locally (measured, mos_tt/1.20 V/27 C); the per-unit cost
        # in a fleet job is much higher, so the budget is generous. 3 units x 1100 s fits the
        # 3600 s job ceiling, the same split sim/clock-path uses.
        "options": {"osdi_preload": pvt_full.osdi_preload(),
                    "timeout_s": 1100},
    }


def request_tt():
    """The single-corner local debug probe, same deck and same measurements.

    `mos_tt` / 1.20 V / 27 C on the local backend: what the bench is checked with before a
    45-corner grid is submitted to the fleet, and what reproduces the negative control
    cheaply. It is a probe, never design evidence -- no record is written from it.

        cd sim/redundancy-mux && klt sim request_tt.json --backend local \\
            --report-out /tmp/rm_tt.json --format json
    """
    r = request()
    r["backend"] = "local"
    r["corners"] = pvt_full.corners(SUPPLIES, only=["tt"], supply_v=[1.2], temperature_c=[27])
    r.pop("batch")
    r["options"] = dict(r["options"], timeout_s=300)
    return r


def outputs():
    return {"redundancy_mux_stim.inc": stim_include(),
            "request.json": json.dumps(request(), indent=2) + "\n",
            "request_tt.json": json.dumps(request_tt(), indent=2) + "\n"}


def main(argv):
    stale = []
    for name, text in outputs().items():
        path = HERE / name
        if "--check" in argv:
            if not path.exists() or path.read_text() != text:
                stale.append(name)
        else:
            path.write_text(text)
    if stale:
        print("stale generated files: " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
